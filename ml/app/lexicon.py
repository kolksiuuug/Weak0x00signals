"""Лексиконы маркеров: слабость / зрелость / хайп.

Единственный источник правды по словарям — используется и признаками (features.py),
и фильтром зрелости (maturity.py), чтобы объяснение модели и причина отклонения
опирались на одни и те же формулировки.

Почему регулярные выражения, а не эмбеддинги: CLAUDE.md §2.2 требует интерпретируемости.
Сработавший маркер можно показать жюри дословно («в тексте найдено: "посевной раунд"»),
а вклад эмбеддинга — нельзя.

Все шаблоны пишутся под текст, уже прошедший normalize_ru(): нижний регистр, ё -> е.
"""

from __future__ import annotations

import re
from typing import Dict, List, Pattern, Tuple


def normalize_ru(text: str) -> str:
    """Нижний регистр, ё -> е, схлопнутые пробелы. Обязателен перед поиском маркеров."""
    if not text:
        return ""
    text = text.replace("ё", "е").replace("Ё", "Е")
    return re.sub(r"\s+", " ", text).strip().lower()


#: Маркер -> (регулярное выражение, человекочитаемое название для объяснения).
#: Название попадает в поле `why` ответа /score, поэтому пишется по-русски и без жаргона.

