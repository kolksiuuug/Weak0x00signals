#: Сколько символов перед совпадением просматриваем в поисках отрицания.
NEGATION_WINDOW = 40

#: Отрицание непосредственно перед маркером переворачивает его смысл:
#: «нет отраслевого стандарта» — это признак НЕзрелости, а не зрелости.
#: Допускаем до двух слов между отрицанием и маркером («не имеет отраслевого стандарта»).
NEGATION_RE = re.compile(r"(?:\bне\b|\bнет\b|\bбез\b|отсутству\w*|отсутстви\w*|\bни\b)"
                         r"(?:\s+\S+){0,2}\s*$")


def _compile(markers: Dict[str, Tuple[str, str]]) -> Dict[str, Tuple[Pattern, str]]:
    return {key: (re.compile(pattern), label) for key, (pattern, label) in markers.items()}


_WEAKNESS = _compile(WEAKNESS_MARKERS)
_MATURITY = _compile(MATURITY_MARKERS)
_HYPE = _compile(HYPE_MARKERS)


def _negated(norm: str, start: int) -> bool:
    """Стоит ли непосредственно перед совпадением отрицание."""
    return bool(NEGATION_RE.search(norm[max(0, start - NEGATION_WINDOW):start]))


def _find(text: str, compiled: Dict[str, Tuple[Pattern, str]],
          honor_negation: bool = False) -> List[str]:
    norm = normalize_ru(text)
    if not norm:
        return []
    out: List[str] = []
    for _, (pattern, label) in compiled.items():
        for match in pattern.finditer(norm):
            if honor_negation and _negated(norm, match.start()):
                continue          # отрицание — маркер не засчитываем
            out.append(label)
            break                 # один маркер учитывается один раз
    return out


def weakness_hits(text: str) -> List[str]:
    """Человекочитаемые маркеры слабости, найденные в тексте.

    Отрицания здесь НЕ фильтруются намеренно: часть маркеров слабости сама
    сформулирована через отрицание («нет коммерческих внедрений», «отсутствие
    стандартов»), и такой фильтр вырезал бы их вместе с ложными срабатываниями.
    """
    return _find(text, _WEAKNESS)


def maturity_hits(text: str) -> List[str]:
    """Человекочитаемые маркеры зрелости технологии (с учётом отрицаний)."""
    return _find(text, _MATURITY, honor_negation=True)


def hype_hits(text: str) -> List[str]:
    """Человекочитаемые маркеры маркетингового хайпа и инфошума (с учётом отрицаний)."""
    return _find(text, _HYPE, honor_negation=True)


